def check_request(text: str) -> str:
    """Проверяет запрос на запрещённые темы. Возвращает 'OK' если всё чисто, иначе — объяснение."""
    if not text:
        return "OK"
    low = text.lower()
    for rule in BLOCKED:
        for kw in rule["keywords"]:
            if kw in low:
                return (
                    f"⛔ Запрос отклонён по юридическим причинам.\n\n"
                    f"📜 {rule['law']}\n"
                    f"Причина: {rule['reason']}\n"
                    f"Ответственность: {rule['punish']}\n\n"
                    f"Я не могу помочь с этим запросом."
                )
    return "OK"


def get_laws_list() -> str:
    """Показывает, какие темы запрещены."""
    lines = ["📜 Запрещённые темы (по УК РФ):"]
    for rule in BLOCKED:
        lines.append(f"• {rule['law']}\n  {rule['reason']}")
    return "\n".join(lines)


